<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\SoftDeletes;

class JobCard extends Model
{
    use HasFactory, SoftDeletes;

    public const JOB_CARD_NO_PREFIX = 'JC-';

    protected $fillable = [
        'job_card_no', 'job_date', 'customer_id', 'vehicle_id', 'odometer_reading_km',
        'job_type', 'assigned_technician_id', 'supervisor_id',
        'promised_delivery_date', 'promised_delivery_time', 'status',
        'discount_percent', 'discount_amount', 'gst_applicable',
        'cgst_amount', 'sgst_amount', 'round_off_amount', 'grand_total',
        'remarks', 'invoice_generated_at', 'estimate_generated_at', 'external_ref',
    ];

    protected $casts = [
        'job_date' => 'date',
        'promised_delivery_date' => 'date',
        'odometer_reading_km' => 'integer',
        'discount_percent' => 'decimal:2',
        'discount_amount' => 'decimal:2',
        'gst_applicable' => 'boolean',
        'cgst_amount' => 'decimal:2',
        'sgst_amount' => 'decimal:2',
        'round_off_amount' => 'decimal:2',
        'grand_total' => 'decimal:2',
        'invoice_generated_at' => 'datetime',
        'estimate_generated_at' => 'datetime',
    ];

    protected static function boot()
    {
        parent::boot();

        static::creating(function ($jobCard) {
            if (empty($jobCard->job_card_no)) {
                $jobCard->job_card_no = self::generateJobCardNo();
            }

            // Defensive default: never persist NULL money fields, even if a
            // future code path explicitly passes null at creation time. The
            // migration already defaults these to 0; this guards the model too.
            // grand_total is deliberately excluded — it stays NULL until the
            // card is billed, which is what makes is_billed / 'unbilled' work.
            foreach (['discount_amount', 'cgst_amount', 'sgst_amount', 'round_off_amount'] as $moneyField) {
                if ($jobCard->{$moneyField} === null) {
                    $jobCard->{$moneyField} = 0;
                }
            }
        });

        static::deleting(function ($jobCard) {
            // Soft-deleting the card intentionally leaves its payment rows
            // alone: the financial history stays fully intact and recoverable
            // with the document. (Previously this hook hard-deleted them.)
        });

        static::forceDeleted(function ($jobCard) {
            // A permanent removal takes its payment records with it — the
            // legacy behaviour for true deletions.
            $jobCard->payments()->get()->each->forceDelete();
        });
    }

    /**
     * Generate the next sequential job card number.
     *
     * The next number is derived from the highest existing numeric suffix in
     * the database (not from the last inserted row), so gaps, out-of-order
     * inserts and manually seeded rows cannot reset or duplicate the sequence.
     * The unique index on job_card_no is the final safety net: if two writers
     * race between generation and insert, one receives a QueryException
     * instead of silently persisting a duplicate.
     */
    public static function generateJobCardNo(): string
    {
        // Soft-deleted rows still occupy their number through the unique
        // index, so the sequence must be derived from every row, trashed
        // included.
        $maxSuffix = (int) self::withTrashed()
            ->selectRaw('MAX(CAST(substr(job_card_no, ?) AS INTEGER)) as max_suffix', [strlen(self::JOB_CARD_NO_PREFIX) + 1])
            ->value('max_suffix');

        $next = $maxSuffix + 1;

        // Defensive skip loop for the tiny window where a candidate was
        // generated by another process that has not committed yet.
        while (self::withTrashed()->where('job_card_no', self::formatJobCardNo($next))->exists()) {
            $next++;
        }

        return self::formatJobCardNo($next);
    }

    public static function formatJobCardNo(int $number): string
    {
        return self::JOB_CARD_NO_PREFIX.str_pad((string) $number, 4, '0', STR_PAD_LEFT);
    }

    public function customer()
    {
        return $this->belongsTo(Customer::class);
    }

    public function vehicle()
    {
        return $this->belongsTo(Vehicle::class);
    }

    public function assignedTechnician()
    {
        return $this->belongsTo(Employee::class, 'assigned_technician_id');
    }

    public function supervisor()
    {
        return $this->belongsTo(Employee::class, 'supervisor_id');
    }

    public function complaints()
    {
        return $this->hasMany(JobCardComplaint::class);
    }

    public function parts()
    {
        return $this->hasMany(JobCardPart::class);
    }

    public function labours()
    {
        return $this->hasMany(JobCardLabour::class);
    }

    public function payments()
    {
        return $this->morphMany(Payment::class, 'payable');
    }

    /**
     * Get the total amount paid via all payments.
     *
     * Uses the eager-loaded payments_sum_amount (added via withSum) when the
     * model was loaded through an index/list query; otherwise falls back to a
     * live SUM query so single-record contexts stay correct.
     */
    public function getAmountPaidAttribute()
    {
        if (array_key_exists('payments_sum_amount', $this->attributes)) {
            return (float) ($this->attributes['payments_sum_amount'] ?? 0);
        }

        return $this->payments()->sum('amount');
    }

    /**
     * Get the outstanding amount (remaining balance).
     *
     * grand_total is NULL until the card is billed, which coerces to 0 — an
     * un-billed card simply owes nothing yet.
     */
    public function getOutstandingAttribute()
    {
        return max(0, (float) $this->grand_total - $this->amount_paid);
    }

    /**
     * Determine whether the card has been billed.
     *
     * IMPORTANT: grand_total stays NULL until updateAssign computes and persists
     * the document totals. A non-null grand_total is the SINGLE SOURCE OF TRUTH
     * for "billed" state.
     *
     * Why this works:
     * - A newly created job card has grand_total = NULL (unbilled)
     * - Once updateAssign runs, grand_total is set (billed)
     * - A card can have payments without line items (rare but valid)
     * - A card can have totals computed with zero line items (free service)
     *
     * @return bool True if the job card has been billed (totals calculated)
     */
    public function getIsBilledAttribute()
    {
        return $this->grand_total !== null;
    }

    /**
     * Get the derived payment status label.
     *
     * Amounts are rounded to currency precision before comparison so binary
     * float residue (e.g. 0.009999999...) can never flip a label.
     */
    public function getPaymentStatusLabelAttribute()
    {
        if (! $this->is_billed) {
            return 'unbilled';
        }

        $outstanding = round((float) $this->outstanding, 2);
        $amountPaid = round((float) $this->amount_paid, 2);

        if ($outstanding == 0.0 && $amountPaid > 0.0) {
            return 'paid';
        }

        if ($amountPaid > 0.0 && $outstanding > 0.0) {
            return 'partially_paid';
        }

        return 'unpaid';
    }
}
