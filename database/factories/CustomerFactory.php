<?php

namespace Database\Factories;

use App\Models\Customer;
use Illuminate\Database\Eloquent\Factories\Factory;

/**
 * @extends Factory<Customer>
 */
class CustomerFactory extends Factory
{
    protected $model = Customer::class;

    /**
     * Define the model's default state.
     *
     * @return array<string, mixed>
     */
    public function definition(): array
    {
        return [
            'first_name' => fake()->firstName(),
            'last_name' => fake()->lastName(),
            'surname' => fake()->optional(0.3)->lastName(),
            'company_name' => fake()->optional(0.2)->company(),
            'display_name' => null, // Will be auto-generated by model boot method
            'mobile' => fake()->numerify('##########'),
            'alt_mobile' => fake()->optional(0.3)->numerify('##########'),
            'email' => fake()->optional(0.5)->safeEmail(),
            'address' => fake()->optional(0.6)->streetAddress(),
            'city' => fake()->optional(0.6)->city(),
            'gstin' => fake()->optional(0.1)->regexify('[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z]{1}[1-9A-Z]{1}Z[0-9A-Z]{1}'),
            'external_ref' => fake()->optional(0.2)->uuid(),
        ];
    }
}
